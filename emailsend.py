import smtplib
from email.message import EmailMessage
import os
import glob
import csv
import logging
import time
from logging.handlers import TimedRotatingFileHandler


EMAIL_MAX_RETRIES = 3

EMAIL_LOG_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "logs", "email")
os.makedirs(EMAIL_LOG_DIR, exist_ok=True)

email_logger = logging.getLogger("emailsend")
email_logger.setLevel(logging.INFO)
email_logger.propagate = False

if not email_logger.handlers:
    email_handler = TimedRotatingFileHandler(
        os.path.join(EMAIL_LOG_DIR, "email-send.log"),
        when="midnight",
        interval=1,
        backupCount=30,
        encoding="utf-8",
    )
    email_handler.setFormatter(logging.Formatter(
        "%(asctime)s [%(levelname)s] %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    ))
    email_logger.addHandler(email_handler)



def calculate_stats(csv_path):
    in_weights = []
    out_weights = []

    with open(csv_path, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                now_w = float(row["now_weight"])
                final_w = float(row["final_weight"])
                diff = abs(final_w - now_w)

                if now_w > final_w:
                    # OUT: weight decreased (sprayer dispensed)
                    out_weights.append(diff)
                else:
                    # IN: weight increased (tank filled)
                    in_weights.append(diff)
            except (ValueError, KeyError):
                continue

    total_records = len(in_weights) + len(out_weights)
    total_in = sum(in_weights)
    total_out = sum(out_weights)
    avg_in = total_in / len(in_weights) if in_weights else 0
    avg_out = total_out / len(out_weights) if out_weights else 0

    return {
        "total_records": total_records,
        "in_count": len(in_weights),
        "out_count": len(out_weights),
        "total_in": total_in,
        "total_out": total_out,
        "avg_in": avg_in,
        "avg_out": avg_out,
    }


